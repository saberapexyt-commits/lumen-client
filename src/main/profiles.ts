import * as fs from 'fs';
import * as path from 'path';
import { P, ensureDir } from './paths';
import { LauncherError, logger } from './logger';
import { LoaderId, LOADERS, assertLoaderSupports } from './loaders';
import { getManifest } from './minecraft/versions';
import { readJson, slugify, writeJson } from './util';

const log = logger('profiles');

export interface Profile {
  id: string;
  name: string;
  color: string;
  mcVersion: string;
  loader: LoaderId;
  loaderVersion?: string;
  /** Launchable version id once installed (e.g. "fabric-loader-0.16.5-1.21.1"). */
  launchVersionId?: string;
  ramMb?: number; // undefined => use global default
  jvmPreset: 'default' | 'aikar' | 'low-latency';
  jvmArgs: string;
  javaPath: string;
  width?: number;
  height?: number;
  fullscreen: boolean;
  notes: string;
  createdAt: number;
  lastPlayed?: number;
  playTimeMs: number;
  source?: { kind: 'mrpack' | 'curseforge' | 'backup'; name: string };
}

