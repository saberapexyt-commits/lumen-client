export async function listProfiles(): Promise<Profile[]> {
  const dir = P.profiles();
  if (!fs.existsSync(dir)) return [];
  const out: Profile[] = [];
  for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!d.isDirectory()) continue;
    const p = await readJson<Profile | null>(P.profileMeta(d.name), null);
    if (p?.id) out.push(p);
  }
  return out.sort((a, b) => (b.lastPlayed ?? b.createdAt) - (a.lastPlayed ?? a.createdAt));
}

export async function getProfile(id: string): Promise<Profile> {
  // ids are generated by us; still guard against traversal coming over IPC.
  if (!/^[a-z0-9-]+$/.test(id)) throw new LauncherError('Invalid profile id.');
  const p = await readJson<Profile | null>(P.profileMeta(id), null);
  if (!p) throw new LauncherError('That profile no longer exists.');
  return p;
}

export async function saveProfile(p: Profile) {
  await writeJson(P.profileMeta(p.id), p);
}

export interface CreateProfileInput {
  name: string;
  mcVersion: string;
  loader: LoaderId;
  loaderVersion?: string;
  color?: string;
  ramMb?: number;
  source?: Profile['source'];
}

function uniqueId(name: string): string {
  const base = slugify(name);
  let id = base;
  for (let i = 2; fs.existsSync(P.profile(id)); i++) id = `${base}-${i}`;
  return id;
}

const COLORS = ['#2f8fe8', '#1fb5a8', '#e5a82b', '#4cb871', '#e0674f', '#7a7fe0', '#c9569a', '#5b8bb0'];

export async function createProfile(input: CreateProfileInput): Promise<Profile> {
  const name = input.name.trim();
  if (!name) throw new LauncherError('Please enter a profile name.');
  const manifest = await getManifest();
  if (!manifest.versions.some((v) => v.id === input.mcVersion)) throw new LauncherError(`Minecraft ${input.mcVersion} does not exist.`);
  // Verify the loader supports this exact Minecraft version *before* creating anything.
  const loaderVersion = await assertLoaderSupports(input.loader, input.mcVersion, input.loaderVersion);

  const id = uniqueId(name);
  const profile: Profile = {
    id,
    name,
    color: input.color ?? COLORS[Math.floor(Math.random() * COLORS.length)],
    mcVersion: input.mcVersion,
    loader: input.loader,
    loaderVersion,
    ramMb: input.ramMb,
    jvmPreset: 'default',
    jvmArgs: '',
    javaPath: '',
    fullscreen: false,
    notes: '',
    createdAt: Date.now(),
    playTimeMs: 0,
    source: input.source,
  };
  ensureDir(P.modsDir(id));
  await saveProfile(profile);
  log.info(`Created profile ${id} (${profile.mcVersion} ${profile.loader} ${loaderVersion ?? ''})`);
  return profile;
}

export async function updateProfile(id: string, patch: Partial<Profile>): Promise<Profile> {
  const cur = await getProfile(id);
  const next: Profile = { ...cur, ...patch, id: cur.id, createdAt: cur.createdAt };
  const gameChanged = next.mcVersion !== cur.mcVersion || next.loader !== cur.loader || next.loaderVersion !== cur.loaderVersion;
  if (gameChanged) {
    next.loaderVersion = await assertLoaderSupports(next.loader, next.mcVersion, patch.loaderVersion && patch.loaderVersion !== cur.loaderVersion ? patch.loaderVersion : undefined);
    next.launchVersionId = undefined; // force re-install on next play
    // Mods built for the old version/loader stay on disk; the Mods page flags them as incompatible.
  }
  await saveProfile(next);
  return next;
}

/** Copy a profile (mods, configs, saves are all copied; nothing is shared with the original). */
export async function duplicateProfile(id: string): Promise<Profile> {
  const src = await getProfile(id);
  const newId = uniqueId(`${src.name} copy`);
  await fs.promises.cp(P.profile(id), P.profile(newId), {
    recursive: true,
    filter: (s) => !s.startsWith(P.backups(id)) && !s.startsWith(P.trash(id)),
  });
  const copy: Profile = { ...src, id: newId, name: `${src.name} copy`, createdAt: Date.now(), lastPlayed: undefined, playTimeMs: 0 };
  await saveProfile(copy);
  return copy;
}

/** Profiles are moved aside, never destroyed outright. */
export async function deleteProfile(id: string): Promise<string> {
  await getProfile(id);
  const dest = path.join(ensureDir(P.deletedProfiles()), `${id}-${Date.now()}`);
  await fs.promises.rename(P.profile(id), dest);
  log.info(`Profile ${id} moved to ${dest}`);
  return dest;
}

export function loaderLabel(p: Pick<Profile, 'loader'>): string {
  return p.loader === 'vanilla' ? 'Vanilla' : LOADERS[p.loader].name;
}
